  function lang() {
    if (window.JOLang) return window.JOLang.get();
    return localStorage.getItem("japanoffer_lang") || "en";
  }

  function t(key, vars) {
    var l = lang();
    var str = (dict[l] && dict[l][key]) || dict.en[key] || dict.zh[key] || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        str = str.split("{" + k + "}").join(String(vars[k]));
      });
    }
    return str;
  }

  function apply() {
    var l = lang();
    var d = dict[l] || dict.en;
    document.documentElement.lang = l === "zh" ? "zh-CN" : l;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var v = d[el.dataset.i18n];
      if (v !== undefined) el.textContent = v;
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var v = d[el.dataset.i18nHtml];
      if (v !== undefined) el.innerHTML = v;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var v = d[el.dataset.i18nPlaceholder];
      if (v !== undefined) el.setAttribute("placeholder", v);
    });
    document.querySelectorAll("[data-i18n-value]").forEach(function (el) {
      var v = d[el.dataset.i18nValue];
      if (v !== undefined) el.value = v;
    });
  }

  window.JOAppsLang = { apply: apply, t: t, lang: lang, dict: dict };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", apply);
  } else {
    apply();
  }
  window.addEventListener("japanoffer:languagechange", apply);
  window.addEventListener("storage", apply);
  setTimeout(apply, 300);
